import { Router } from 'express';
import { patientController } from '../controllers/patient.controller.js';
import { authenticate } from '../middleware/authenticate.js';
import { authorize } from '../middleware/authorize.js';
import { validate } from '../middleware/validate.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import { idParams, patientListQuery } from '../validators/common.validator.js';
import { createPatientSchema, patientNoticeSchema, patientPasswordSchema, updatePatientSchema } from '../validators/patient.validator.js';
import { activeSchema } from '../validators/common.validator.js';

export const patientRoutes=Router();
patientRoutes.use(authenticate);
patientRoutes.get('/my-notices',authorize('PATIENT'),asyncHandler(patientController.myNotices));
patientRoutes.get('/me/health-record',authorize('PATIENT'),asyncHandler(patientController.myHealthRecord));
patientRoutes.get('/',authorize('ADMIN','PHARMACIST','CASHIER'),validate({query:patientListQuery}),asyncHandler(patientController.list));
patientRoutes.use(authorize('ADMIN','PHARMACIST'));
patientRoutes.get('/:id/health-record',validate({params:idParams}),asyncHandler(patientController.healthRecord));
patientRoutes.post('/:id/notices',validate({params:idParams,body:patientNoticeSchema}),asyncHandler(patientController.createNotice));
patientRoutes.post('/',validate({body:createPatientSchema}),asyncHandler(patientController.create));
patientRoutes.put('/:id',validate({params:idParams,body:updatePatientSchema}),asyncHandler(patientController.update));
patientRoutes.post('/:id/reset-password',validate({params:idParams,body:patientPasswordSchema}),asyncHandler(patientController.resetPassword));
patientRoutes.patch('/:id/active',authorize('ADMIN','PHARMACIST'),validate({params:idParams,body:activeSchema}),asyncHandler(patientController.setActive));
patientRoutes.delete('/:id',validate({params:idParams}),asyncHandler(patientController.remove));
